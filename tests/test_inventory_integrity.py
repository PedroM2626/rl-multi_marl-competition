"""The published SHA-256 column must be reproducible from a clone, on any platform.

docs/09 section 9.7 is the repository's integrity mechanism: 172 rows of path, byte count and hash for the
versioned artefacts. It was generated by hashing the file on disk, and this host checks text files out with
CRLF (`core.autocrlf=true`) while the repository stores LF -- so for every text artefact the published hash
described one particular checkout configuration and no reader on Linux could reproduce it. Binary artefacts
were never affected, which is why the defect survived: the checkpoints, the largest entries, all verified.

`scripts/report_inventory.py` now hashes `git cat-file blob HEAD:<path>`, the committed bytes. Checked here
against the same objects Git itself reports, in one batched call, so the gate costs milliseconds and covers
every row rather than a sample.
"""

from __future__ import annotations

import hashlib
import re
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "09_reproducibility.md"
ROW = re.compile(r"^\| `([^`]+)` \| ([\d,]+) \| `([0-9a-f]{64})` \|$")


def inventory_rows() -> list[tuple[str, int, str]]:
    section = re.search(r"^## 9\.7 Artefact inventory.*?(?=^## 9\.8)",
                        DOC.read_text(encoding="utf-8"), re.S | re.M).group(0)
    rows = []
    for line in section.splitlines():
        match = ROW.match(line.strip())
        if match and match.group(1) != "Path":
            rows.append((match.group(1), int(match.group(2).replace(",", "")), match.group(3)))
    return rows


_CACHE: dict[str, bytes] = {}


def committed_blobs(paths: list[str]) -> dict[str, bytes]:
    """The committed objects for `paths`, read in one `git cat-file --batch` pass and memoised."""
    missing = [p for p in paths if p not in _CACHE]
    if missing:
        proc = subprocess.run(["git", "cat-file", "--batch"], cwd=ROOT,
                              input=b"".join(f"HEAD:{p}\n".encode("utf-8") for p in missing),
                              capture_output=True, check=True).stdout
        position = 0
        for path in missing:
            end = proc.index(b"\n", position)
            header = proc[position:end].split()
            position = end + 1
            if len(header) == 3 and header[1] == b"blob":
                size = int(header[2])
                _CACHE[path] = proc[position:position + size]
                position += size + 1
            else:
                _CACHE[path] = b""
                position = proc.index(b"\n", position) + 1
    return {path: _CACHE[path] for path in paths}


def test_every_published_hash_is_the_committed_bytes() -> None:
    rows = inventory_rows()
    assert len(rows) > 150, rows
    blobs = committed_blobs([row[0] for row in rows])
    for path, size, digest in rows:
        blob = blobs[path]
        assert blob, f"{path} is not readable as a committed blob"
        assert size == len(blob), f"{path}: the byte column is not the committed size"
        assert digest == hashlib.sha256(blob).hexdigest(), f"{path}: hash is not the committed object"


def test_the_hash_column_is_not_the_working_tree_for_text_artefacts() -> None:
    """The specific defect: a text artefact whose checkout differs from its blob must publish the blob."""
    rows = {path: (size, digest) for path, size, digest in inventory_rows()}
    text = "results/study/per_seed_metrics.csv"
    size, digest = rows[text]
    assert digest == hashlib.sha256(committed_blobs([text])[text]).hexdigest()
    on_disk = (ROOT / text).read_bytes()
    if on_disk == committed_blobs([text])[text]:
        pytest.skip(f"{text} is checked out with LF on this host, so the two forms agree and the "
                    f"discriminating case cannot be observed")
    assert digest != hashlib.sha256(on_disk).hexdigest(), \
        "the table would be publishing the CRLF form again"


def test_the_claimed_file_count_matches_the_table() -> None:
    """The generator writes the count into the sentence above the table; a hand-edit must not drift from it."""
    rows = inventory_rows()
    claimed = int(re.search(r"Every versioned experiment artefact \((\d+) files\)",
                            DOC.read_text(encoding="utf-8")).group(1))
    assert claimed == len(rows), (claimed, len(rows))


def test_no_artefact_is_listed_twice_or_missing() -> None:
    listing = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.splitlines()
    versioned = {p for p in listing if p.startswith(
        ("data/", "ctde_arena/data/", "exports/", "ctde_arena/exports/", "results/",
         "ctde_arena/results/", "docs/assets/", "requirements-measured.lock.txt",
         "ctde_arena/requirements-measured.lock.txt", "LICENSE"))}
    published = [path for path, _, _ in inventory_rows()]
    assert len(published) == len(set(published)), "a duplicated row"
    assert set(published) == versioned, (sorted(versioned - set(published)),
                                         sorted(set(published) - versioned))
